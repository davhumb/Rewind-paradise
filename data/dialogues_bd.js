// ===================================================
// FONCTION POUR RÉCUPÉRER UN DIALOGUE
// ===================================================

function getDialogueBD(situation) {
  const pool = DIALOGUES_BD[situation];
  if (!pool || pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}

// ===================================================
// AFFICHER LES BULLES BD
// ===================================================

function afficherBullesBD(situation, container, callback) {
  const dialogue = getDialogueBD(situation);
  if (!dialogue || !container) {
    if (callback) callback();
    return;
  }

  container.innerHTML = '';
  let index = 0;

  function afficherReplique() {
    if (index >= dialogue.length) {
      // Effacer après lecture
      setTimeout(() => {
        container.style.opacity = '0';
        container.style.transition = 'opacity 0.5s';
        setTimeout(() => {
          container.innerHTML = '';
          container.style.opacity = '1';
          if (callback) callback();
        }, 500);
      }, 2000);
      return;
    }

    const rep    = dialogue[index];
    const isFred = rep.perso === 'fred';

    const bulle = document.createElement('div');
    bulle.style.cssText = `
      display: flex;
      justify-content: ${isFred ? 'flex-start' : 'flex-end'};
      margin-bottom: 6px;
      animation: bulleAppear 0.2s ease;
    `;

    bulle.innerHTML = `
      <div style="
        max-width: 75%;
        background: ${isFred ? '#0f0f2a' : '#1a0f05'};
        border: 1px solid ${isFred ? '#3a3a6a' : '#ff885530'};
        border-radius: ${isFred
          ? '4px 12px 12px 12px'
          : '12px 4px 12px 12px'};
        padding: 7px 10px;
        position: relative;
        font-size: 11px;
        color: ${isFred ? '#9090cc' : '#cc9966'};
        font-style: italic;
        line-height: 1.4;
        letter-spacing: 0.3px;
      ">
        ${rep.texte}
      </div>
    `;

    container.appendChild(bulle);
    index++;

    const delai = rep.texte.length * 30 + 400;
    setTimeout(afficherReplique, Math.min(delai, 2000));
  }

  afficherReplique();
}